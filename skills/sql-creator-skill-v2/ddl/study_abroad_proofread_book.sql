  `qs_ranking` int(11) DEFAULT NULL COMMENT 'QS排名',
  `academic_requirements` varchar(2000) DEFAULT NULL COMMENT '学术要求',
  `language_requirements` varchar(2000) DEFAULT NULL COMMENT '语言要求',
  `written_test_requirements` varchar(2000) DEFAULT NULL COMMENT '笔试要求',
  `study_abroad_major_id` bigint(20) DEFAULT NULL COMMENT '专业方向ID',
