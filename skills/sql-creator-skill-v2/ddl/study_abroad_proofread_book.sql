  `student_id` bigint(11) NOT NULL COMMENT '学生ID',
  `application_country` varchar(255) NOT NULL COMMENT '申请国家',
  `application_school` varchar(255) NOT NULL COMMENT '申请学校',
  `application_major` varchar(255) NOT NULL COMMENT '申请专业',
  `course_code` varchar(255) DEFAULT NULL COMMENT '课程代码',
  `course_website_address` varchar(500) DEFAULT NULL COMMENT '课程网址地址',
  `status` int(11) NOT NULL DEFAULT '0' COMMENT '定校状态（0-未定校、1-已定校）',
  `del` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否被删除（0表示未删除，1表示已删除）',
