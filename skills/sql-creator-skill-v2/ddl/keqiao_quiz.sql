CREATE TABLE `keqiao_quiz` (
  `id` bigint(11) NOT NULL AUTO_INCREMENT,
  `name` varchar(255) NOT NULL COMMENT '考试名称',
  `keqial_quiz_type` int(11) NOT NULL COMMENT '考试类型ID',
  `edu_level_mapping_id` bigint(11) DEFAULT NULL COMMENT '等级映射规则ID',
  `is_keqial_quiz_type` int(11) DEFAULT NULL COMMENT '计入的考试类型',
  `time_start` bigint(11) NOT NULL COMMENT '考试开始时间（时间戳）',
  `time_end` bigint(11) NOT NULL COMMENT '考试结束时间（时间戳）',
  `grade_type` int(11) NOT NULL COMMENT '成绩类型1分数 2等级 3分数/等级',
  `score` int(11) NOT NULL COMMENT '最高分（100分 = 10000）',
  `num` int(11) NOT NULL COMMENT '月考次数',
  `keqiao_class_id` bigint(11) NOT NULL COMMENT '班级ID',
  `admin_user_id` int(11) NOT NULL COMMENT '操作人ID',
  `created_time` bigint(11) NOT NULL COMMENT '创建时间',
  `update_time` bigint(11) DEFAULT NULL COMMENT '更新时间',
  `rel` int(11) NOT NULL DEFAULT '0' COMMENT '成绩是否发布0下线1上线2发布成绩（本条数据无法再修改）',
  `del` int(11) NOT NULL DEFAULT '0',
  `involved_content` varchar(1024) DEFAULT NULL COMMENT '本次测试涉及内容',
  `test_analysis` varchar(1024) DEFAULT NULL COMMENT '本次测试整体考情分析',
  PRIMARY KEY (`id`),
  KEY `keqiao_quiz_1` (`keqial_quiz_type`) USING BTREE,
  KEY `keqiao_quiz_2` (`keqiao_class_id`) USING BTREE,
  KEY `keqiao_quiz_3` (`admin_user_id`) USING BTREE,
  KEY `keqiao_quiz_4` (`is_keqial_quiz_type`) USING BTREE,
  KEY `keqiao_quiz_5` (`edu_level_mapping_id`) USING BTREE,
  CONSTRAINT `keqiao_quiz_ibfk_1` FOREIGN KEY (`keqial_quiz_type`) REFERENCES `keqiao_quiz_type` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT `keqiao_quiz_ibfk_2` FOREIGN KEY (`keqiao_class_id`) REFERENCES `keqiao_class` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT `keqiao_quiz_ibfk_3` FOREIGN KEY (`admin_user_id`) REFERENCES `admin_user` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT `keqiao_quiz_ibfk_4` FOREIGN KEY (`is_keqial_quiz_type`) REFERENCES `keqiao_quiz_type` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT `keqiao_quiz_ibfk_5` FOREIGN KEY (`edu_level_mapping_id`) REFERENCES `edu_level_mapping` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION
) ENGINE=InnoDB AUTO_INCREMENT=486 DEFAULT CHARSET=utf8mb4 COMMENT='考试测验'