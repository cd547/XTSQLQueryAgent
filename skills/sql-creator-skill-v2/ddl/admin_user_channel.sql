  `back_name` varchar(255) DEFAULT NULL COMMENT '开户行',
  `protocol` int(11) DEFAULT NULL COMMENT '是否签署协议 1已签署 2未签署',
  `my_contract_company` varchar(255) DEFAULT NULL COMMENT '我放签约公司',
  `contract_time` bigint(11) DEFAULT NULL COMMENT '签约日期',
