  `to_post` varchar(255) DEFAULT NULL COMMENT '所在岗位',
  `category` varchar(255) NOT NULL COMMENT '渠道类别',
  `protocol_version` int(11) DEFAULT '1' COMMENT '协议版本 1 其他 2 22年通用 3 24年通用',
